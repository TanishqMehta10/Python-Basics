# Variables-> Name given to memory location in a program
# Variable can store data and we can use that data later in the program
# Variable can store different types of data like numbers, text, list, etc. 

# Example of variable
# Creating a variable and storing a number in it
a = 10
# Creating a variable and storing a string in it
name = "Tanishq"
# Creating a variable and storing a list in it
my_list = [1, 2, 3, 4, 5]
# Creating a variable and storing the result of an operation in it
result = a + 5
# Printing the variables
print(a) # Output: 10
print(name) # Output: Tanishq
print(my_list) # Output: [1, 2, 3, 4, 5]
print(result) # Output: 15
